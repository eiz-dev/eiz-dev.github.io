#!/usr/bin/env ruby
# Prints the body of the app's lib/src/legal/legal_config.dart with the
# published URLs and support email for one app.
#
#   ruby scripts/legal_config.rb <slug>
require "yaml"
require "date"
require_relative "support_email"

root = File.expand_path("..", __dir__)
slug = ARGV[0] or abort "usage: ruby scripts/legal_config.rb <slug>"

config = YAML.load_file(File.join(root, "_config.yml"))
studio = YAML.load_file(File.join(root, "_data/studio.yml"))
apps = YAML.load_file(File.join(root, "_data/apps.yml"), permitted_classes: [Date])
app = apps[slug] or abort "'#{slug}' is not in _data/apps.yml"

base = config.fetch("url").sub(%r{/\z}, "") + config.fetch("baseurl", "").to_s
languages = config.fetch("languages")

def url_map(base, slug, doc, languages)
  entries = languages.each_with_index.map do |lang, i|
    path = i.zero? ? "/#{slug}/#{doc}/" : "/#{slug}/#{lang}/#{doc}/"
    "  '#{lang}': '#{base}#{path}',"
  end
  "{\n#{entries.join("\n")}\n}"
end

email = support_email(studio, app)

dart = <<~DART
  // Generated by eizdev.github.io/scripts/legal_config.rb #{slug}
  static const Map<String, String> privacyPolicyUrl = #{url_map(base, slug, 'privacy', languages)};

  static const Map<String, String> termsUrl = #{url_map(base, slug, 'terms', languages)};

  static const Map<String, String> impressumUrl = {
    'en': '#{base}/legal-notice/',
  };

  static const Map<String, String> supportUrl = #{url_map(base, slug, 'support', languages)};

  static const String supportEmail = '#{email}';
DART

# Indented to paste straight into the LegalConfig class body.
puts dart.gsub(/^(?=.)/, "  ")
